# §360：影之刃零用的大厅服务端 = 4net 的 fornet/server/fornet-lobby-server.mjs 只换 @wire-defaults 那一行（协议名换回 PBZ 线上一直用的那套）。
# 生成 server/pbz-lobby-server.mjs（进 git；部署到大厅服务器、发布包、测试都用它），README / LICENSE 照拷，README 前面加一段说明。
#   python -X utf8 -I tools/gen_pbz_server.py           生成 / 更新
#   python -X utf8 -I tools/gen_pbz_server.py --check   只检查 server/ 和 fornet/server 对得上（tests/test_wire_names.py 也查）
# 线上格式一个字节都不能变：PBZS| 控制包、PBZR| / PBZW| / PBZV| / PBZU| 转发头、PBZ_ 环境变量、同目录 pbz-ranked.mjs、服务器房默认地图 PBZ_Server；
# 另认 4N| 控制包（0.3x 起服务器就双认，回包用对方来时的前缀）。联机程序那边同一套名字在 mod/PBZ_MP/lobby/PbzGame.cs（WireTag.Configure）。
import io, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "fornet", "server")
DST = os.path.join(ROOT, "server")
PBZ_DEFAULTS = ("const WIRE_DEFAULTS = { server: 'PBZS', peer: 'PBZ', alias: '4N', env: 'PBZ_', ranked: './pbz-ranked.mjs', map: 'PBZ_Server' };"
                "     // @wire-defaults（影之刃零：tools/gen_pbz_server.py 生成，别手改这个文件）")
README_HEAD = """> **影之刃零（PBZ_MP）用的服务端**：`pbz-lobby-server.mjs` 由 `tools/gen_pbz_server.py` 从 4net 的 `fornet/server/fornet-lobby-server.mjs` 生成，
> 只换了协议名那一行（`@wire-defaults`）：控制包 `PBZS|…`（也认 `4N|…`）、转发头 `PBZR|` / `PBZW|` / `PBZV|` / `PBZU|`、环境变量前缀 `PBZ_`、
> 排位模块默认 `pbz-ranked.mjs`。下文的 `fornet-lobby-server.mjs` / `4N|` / `FORNET_` 对影之刃零来说就是 `pbz-lobby-server.mjs` / `PBZS|` / `PBZ_`。
> 别手改本目录的文件：改 `fornet/server/` 再重新生成。

"""
README_HEAD_EN = """> **The server for PBZ_MP (Phantom Blade Zero)**: `pbz-lobby-server.mjs` is generated by `tools/gen_pbz_server.py` from 4net's
> `fornet/server/fornet-lobby-server.mjs`, changing only the wire-names line (`@wire-defaults`): control packets `PBZS|…` (`4N|…` accepted too),
> forward heads `PBZR|` / `PBZW|` / `PBZV|` / `PBZU|`, environment variable prefix `PBZ_`, ranked module `pbz-ranked.mjs`. Below, read
> `fornet-lobby-server.mjs` / `4N|` / `FORNET_` as `pbz-lobby-server.mjs` / `PBZS|` / `PBZ_`. Don't edit this folder: change `fornet/server/` and regenerate.

"""


def build():
    src = io.open(os.path.join(SRC, "fornet-lobby-server.mjs"), encoding="utf-8").read()
    lines = src.split("\n")
    hits = [i for i, l in enumerate(lines) if "@wire-defaults" in l and l.startswith("const WIRE_DEFAULTS")]
    if len(hits) != 1:
        sys.exit("fornet-lobby-server.mjs 里要正好一行 const WIRE_DEFAULTS … // @wire-defaults，找到 %d 行" % len(hits))
    lines[hits[0]] = PBZ_DEFAULTS
    out = {"pbz-lobby-server.mjs": "\n".join(lines)}
    # 4net 的 README.md 是英文、README.zh.md 是中文（11-16 用户：GitHub 上默认英文）
    out["README.md"] = README_HEAD_EN + io.open(os.path.join(SRC, "README.md"), encoding="utf-8").read()
    out["README.zh.md"] = README_HEAD + io.open(os.path.join(SRC, "README.zh.md"), encoding="utf-8").read()
    out["LICENSE"] = io.open(os.path.join(SRC, "LICENSE"), encoding="utf-8").read()
    return out


def main():
    want = build()
    check = "--check" in sys.argv
    bad = []
    for name, text in want.items():
        p = os.path.join(DST, name)
        have = io.open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if have == text:
            continue
        if check:
            bad.append(name)
        else:
            os.makedirs(DST, exist_ok=True)
            io.open(p, "w", encoding="utf-8", newline="\n").write(text)
            print("写了 server/" + name)
    if check:
        if bad:
            sys.exit("server/ 和 fornet/server 对不上（先跑 python -X utf8 -I tools/gen_pbz_server.py）：" + ", ".join(bad))
        print("server/ 和 fornet/server 一致")


if __name__ == "__main__":
    main()
